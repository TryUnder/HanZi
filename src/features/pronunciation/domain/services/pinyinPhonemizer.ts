type RhymeResult = string | readonly string[];

/**
 * Mandarin rhyme transformations from Charsiu.
 *
 * Values are model phone labels, not standard Pinyin.
 */
const RHYME: Readonly<Record<string, RhymeResult>> = {
  iu1: "iou1",
  iu2: "iou2",
  iu3: "iou3",
  iu4: "iou4",
  iu5: "iou5",

  "u:e1": "ve1",
  "u:e2": "ve2",
  "u:e3": "ve3",
  "u:e4": "ve4",
  "u:e5": "ve5",

  "u:1": "v1",
  "u:2": "v2",
  "u:3": "v3",
  "u:4": "v4",
  "u:5": "v5",

  ueng1: ["u1", "eng1"],
  ueng2: ["u2", "eng2"],
  ueng3: ["u3", "eng3"],
  ueng4: ["u4", "eng4"],
  ueng5: ["u5", "eng5"],

  io1: ["i1", "o1"],
  io4: ["i4", "o4"],
  io5: ["i5", "o5"],
};

function normalizePinyin(value: string): string {
  return value.toLowerCase().replace(/u:/g, "ü").replace(/ü/g, "v");
}

function transformSyllable(syllable: string): string {
  const normalized = normalizePinyin(syllable);

  return TRANSFORM[normalized] ?? normalized;
}

function splitInitialAndFinal(syllable: string): {
  readonly initial: string;
  readonly final: string;
} {
  const initial = INITIALS.find((candidate) => syllable.startsWith(candidate));

  if (!initial) {
    return {
      initial: "",
      final: syllable,
    };
  }

  return {
    initial,
    final: syllable.slice(initial.length),
  };
}

function resolveRhyme(rhyme: string, tone: number): readonly string[] {
  const key = `${rhyme}${tone}`;
  const result = RHYME[key];

  if (typeof result === "string") {
    return [result];
  }

  if (result !== undefined) {
    return result;
  }

  return [key];
}

/**
 * Converts one numbered Pinyin syllable into Charsiu phones.
 *
 * The transformation order intentionally follows the original
 * Charsiu separateSyllable implementation.
 */
function convertSyllableToPhones(
  pinyin: string,
  tone: number,
): readonly string[] {
  const transformed = transformSyllable(pinyin);

  // Charsiu uses a dedicated representation for ri4.
  if (transformed === "ri" && tone === 4) {
    return ["r", "iii4"];
  }

  // Standalone er1-er5 is represented as e + retroflex suffix.
  if (transformed === "er") {
    return [`e${tone}`, "rr"];
  }

  // These rhymes must be resolved before splitting initials.
  if (transformed === "ueng" || transformed === "io") {
    return resolveRhyme(transformed, tone);
  }

  const { initial, final } = splitInitialAndFinal(transformed);

  const phones = initial ? [initial] : [];

  phones.push(...resolveRhyme(final, tone));

  return phones;
}

function createError(
  code: PhonemizationErrorCode,
  message: string,
  details?: {
    readonly syllableIndex?: number;
    readonly syllable?: string;
    readonly phone?: string;
  },
): PhonemizationResult {
  return {
    success: false,
    error: {
      code,
      message,
      ...details,
    },
  };
}

export function phonemizePronunciation(
  realizations: readonly PronunciationSyllableRealization[],
  vocabulary: PhoneVocabulary,
): PhonemizationResult {
  if (realizations.length === 0) {
    return createError(
      "EMPTY_PRONUNCIATION",
      "Cannot phonemize an empty pronunciation.",
    );
  }

  const phonemes: TargetPhoneme[] = [];

  for (
    let syllableIndex = 0;
    syllableIndex < realizations.length;
    syllableIndex += 1
  ) {
    const realization = realizations[syllableIndex];

    if (!realization) {
      return createError(
        "INVALID_PHONE_SEQUENCE",
        "A pronunciation syllable is missing.",
        { syllableIndex },
      );
    }

    const { syllable } = realization;
    const normalizedPinyin = normalizePinyin(syllable.pinyin);

    if (UNSUPPORTED_SYLLABLES.has(normalizedPinyin)) {
      return createError(
        "UNSUPPORTED_SYLLABLE",
        `Pinyin syllable "${syllable.pinyin}" is not supported by the Charsiu phone inventory.`,
        {
          syllableIndex,
          syllable: syllable.pinyin,
        },
      );
    }

    // Align the recording against the tone actually pronounced after sandhi.
    // Keep the lexical reading unchanged for dictionary display.
    const phones = [
      ...convertSyllableToPhones(syllable.pinyin, realization.surfaceTone),
    ];

    /**
     * The parser attaches r5 to the preceding syllable.
     * Charsiu represents r5 as e5 + rr.
     *
     * We preserve our syllable boundary by assigning both
     * phones to the preceding syllable.
     */
    if (syllable.erhua) {
      phones.push("e5", "rr");
    }

    if (phones.length === 0 || phones.some((phone) => !phone)) {
      return createError(
        "UNSUPPORTED_SYLLABLE",
        `Cannot convert Pinyin syllable "${syllable.pinyin}" to phonemes.`,
        {
          syllableIndex,
          syllable: syllable.pinyin,
        },
      );
    }

    for (
      let positionInSyllable = 0;
      positionInSyllable < phones.length;
      positionInSyllable += 1
    ) {
      const symbol = phones[positionInSyllable];

      if (!symbol) {
        return createError(
          "INVALID_PHONE_SEQUENCE",
          "A phoneme is missing from the generated sequence.",
          {
            syllableIndex,
            syllable: syllable.pinyin,
          },
        );
      }

      const vocabularyId = vocabulary[symbol];

      if (vocabularyId === undefined) {
        return createError(
          "MISSING_PHONE",
          `Phoneme "${symbol}" does not exist in the model vocabulary.`,
          {
            syllableIndex,
            syllable: syllable.pinyin,
            phone: symbol,
          },
        );
      }

      phonemes.push({
        symbol,
        vocabularyId,
        syllableIndex,
        positionInSyllable,
      });
    }
  }

  if (phonemes.length === 0) {
    return createError(
      "INVALID_PHONE_SEQUENCE",
      "The generated phoneme sequence is empty.",
    );
  }

  return {
    success: true,
    pronunciation: {
      syllables: realizations.length,
      phonemes,
      phoneIds: phonemes.map((phoneme) => phoneme.vocabularyId),
    },
  };
}
