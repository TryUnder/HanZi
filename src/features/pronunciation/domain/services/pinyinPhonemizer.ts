export type PhonemizationErrorCode =
  | "EMPTY_PRONUNCIATION"
  | "UNSUPPORTED_SYLLABLE"
  | "MISSING_PHONE"
  | "INVALID_PHONE_SEQUENCE";

export interface PhonemizationError {
  readonly code: PhonemizationErrorCode;
  readonly message: string;
  readonly syllableIndex?: number;
  readonly syllable?: string;
  readonly phone?: string;
}

export type PhonemizationResult =
  | {
      readonly success: true;
      readonly pronunciation: PhonemizedPronunciation;
    }
  | {
      readonly success: false;
      readonly error: PhonemizationError;
    };

